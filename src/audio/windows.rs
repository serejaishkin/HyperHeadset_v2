//! Windows Equalizer APO integration
use std::path::PathBuf;
use std::fs;

const APO_CONFIG_PATH: &str = r"C:\Program Files\EqualizerAPO\config\config.txt";
const APO_PRESETS_DIR: &str = r"C:\Program Files\EqualizerAPO\config\presets";

const BAND_FREQUENCIES: [f32; 10] = [
    32.0, 64.0, 125.0, 250.0, 500.0,
    1000.0, 2000.0, 4000.0, 8000.0, 16000.0,
];

pub fn is_apo_installed() -> bool {
    // The config folder alone can be left over after an uninstall: require the Configurator too.
    let cfg = PathBuf::from(APO_CONFIG_PATH);
    cfg.parent().map_or(false, |p| p.exists())
        && cfg.parent().and_then(|p| p.parent()).map_or(false, |root| root.join("Configurator.exe").exists())
}

const APO_OWN_FILE: &str = "hyperx_ngenuity_open.txt";

fn eq_text(bands: &[f32; 10]) -> String {
    // Preamp = -(largest boost) so boosted bands cannot clip.
    let peak = bands.iter().cloned().fold(0.0f32, f32::max);
    let mut t = String::from("; Generated by hyperx_ngenuity_open. Do not edit manually.\n");
    t.push_str(&format!("Preamp: {:.1} dB\n", -peak));
    for (freq, gain) in BAND_FREQUENCIES.iter().zip(bands.iter()) {
        t.push_str(&format!("Filter: ON PK Fc {:.0} Hz Gain {:.1} dB Q 1.41\n", freq, gain));
    }
    t
}

/// Writes our own file next to Equalizer APO's config.txt and makes sure config.txt includes it
/// (the user's existing APO configuration is kept, only one Include line is appended once).
pub fn apply_eq_bands(bands: &[f32; 10]) -> anyhow::Result<()> {
    if !is_apo_installed() {
        return Err(anyhow::anyhow!(crate::tr_pick(
            "Equalizer APO не найден. Установите Equalizer APO (sourceforge.net/projects/equalizerapo), включите его для гарнитуры в Configurator и повторите.",
            "Equalizer APO not found. Install Equalizer APO (sourceforge.net/projects/equalizerapo), enable it for the headset in Configurator and retry.")));
    }
    let cfg = PathBuf::from(APO_CONFIG_PATH);
    let own = cfg.with_file_name(APO_OWN_FILE);
    let perm = |e: std::io::Error| anyhow::anyhow!(
        "Нет прав на запись в папку Equalizer APO ({}). Запустите приложение от имени администратора один раз. ({})", own.display(), e);
    fs::write(&own, eq_text(bands)).map_err(perm)?;
    // Only a missing file counts as empty; any other read error must not lead to overwriting the user's config.
    let main = match fs::read(&cfg) {
        Ok(bytes) => String::from_utf8_lossy(&bytes).into_owned(),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(perm(e)),
    };
    if !main.contains(APO_OWN_FILE) {
        use std::io::Write;
        let mut f = fs::OpenOptions::new().append(true).open(&cfg).map_err(perm)?;
        let prefix = if main.is_empty() || main.ends_with('\n') { "" } else { "\n" };
        write!(f, "{}Include: {}\n", prefix, APO_OWN_FILE).map_err(perm)?;
    }
    log::info!("[WindowsEQ] Applied {} bands via {:?}", bands.len(), own);
    Ok(())
}

pub fn save_preset(name: &str, bands: &[f32; 10]) -> anyhow::Result<()> {
    let preset_dir = PathBuf::from(APO_PRESETS_DIR);
    if !preset_dir.exists() { fs::create_dir_all(&preset_dir)?; }
    let path = preset_dir.join(format!("hyperx_{}.txt", name.to_lowercase().replace(" ", "_")));
    let mut content = String::from("; HyperX preset\n");
    content.push_str("Preamp: -6 dB\n\n");
    for (freq, gain) in BAND_FREQUENCIES.iter().zip(bands.iter()) {
        content.push_str(&format!("Filter: ON PK Fc {:.0} Hz Gain {:.1} dB Q 1.41\n", freq, gain));
    }
    fs::write(&path, content)?;
    log::info!("[WindowsEQ] Saved preset to {:?}", path);
    Ok(())
}

pub fn load_preset(name: &str) -> anyhow::Result<[f32; 10]> {
    let path = PathBuf::from(APO_PRESETS_DIR).join(format!("hyperx_{}.txt", name.to_lowercase().replace(" ", "_")));
    let content = fs::read_to_string(&path)?;
    let mut bands = [0.0f32; 10];
    let mut idx = 0;
    for line in content.lines() {
        if line.starts_with("Filter:") && idx < 10 {
            if let Some(gain_part) = line.split("Gain ").nth(1) {
                if let Some(gain_str) = gain_part.split(" dB").next() {
                    if let Ok(gain) = gain_str.parse::<f32>() { bands[idx] = gain; idx += 1; }
                }
            }
        }
    }
    if idx != 10 { return Err(anyhow::anyhow!("Preset file corrupted")); }
    log::info!("[WindowsEQ] Loaded preset from {:?}", path);
    Ok(bands)
}
