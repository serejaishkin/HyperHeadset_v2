//! Windows Equalizer APO integration
use std::path::PathBuf;
use std::fs;

const APO_CONFIG_PATH: &str = r"C:\Program Files\EqualizerAPO\config\config.txt";
const APO_PRESETS_DIR: &str = r"C:\Program Files\EqualizerAPO\config\presets";

const BAND_FREQUENCIES: [f32; 10] = [
    32.0, 64.0, 125.0, 250.0, 500.0,
    1000.0, 2000.0, 4000.0, 8000.0, 16000.0,
];

pub fn is_apo_installed() -> bool {
    PathBuf::from(APO_CONFIG_PATH).parent().map(|p| p.exists()).unwrap_or(false)
}

const APO_OWN_FILE: &str = "hyperx_ngenuity_open.txt";

fn eq_text(bands: &[f32; 10]) -> String {
    // Preamp = -(largest boost) so boosted bands cannot clip.
    let peak = bands.iter().cloned().fold(0.0f32, f32::max);
    let mut t = String::from("; Generated by hyperx_ngenuity_open. Do not edit manually.\n");
    t.push_str(&format!("Preamp: {:.1} dB\n", -peak));
    for (freq, gain) in BAND_FREQUENCIES.iter().zip(bands.iter()) {
        t.push_str(&format!("Filter: ON PK Fc {:.0} Hz Gain {:.1} dB Q 1.41\n", freq, gain));
    }
    t
}

/// Writes our own file next to Equalizer APO's config.txt and makes sure config.txt includes it
/// (the user's existing APO configuration is kept, only one Include line is appended once).
pub fn apply_eq_bands(bands: &[f32; 10]) -> anyhow::Result<()> {
    if !is_apo_installed() {
        return Err(anyhow::anyhow!(
            "Equalizer APO не найден ({}). Установите Equalizer APO (sourceforge.net/projects/equalizerapo), \
             включите его для гарнитуры в Configurator и повторите.", APO_CONFIG_PATH));
    }
    let cfg = PathBuf::from(APO_CONFIG_PATH);
    let own = cfg.with_file_name(APO_OWN_FILE);
    let perm = |e: std::io::Error| anyhow::anyhow!(
        "Нет прав на запись в папку Equalizer APO ({}). Запустите приложение от имени администратора один раз. ({})", own.display(), e);
    fs::write(&own, eq_text(bands)).map_err(perm)?;
    let main = fs::read_to_string(&cfg).unwrap_or_default();
    if !main.contains(APO_OWN_FILE) {
        let mut out = main;
        if !out.is_empty() && !out.ends_with('\n') { out.push('\n'); }
        out.push_str(&format!("Include: {}\n", APO_OWN_FILE));
        fs::write(&cfg, out).map_err(perm)?;
    }
    log::info!("[WindowsEQ] Applied {} bands via {:?}", bands.len(), own);
    Ok(())
}

pub fn save_preset(name: &str, bands: &[f32; 10]) -> anyhow::Result<()> {
    let preset_dir = PathBuf::from(APO_PRESETS_DIR);
    if !preset_dir.exists() { fs::create_dir_all(&preset_dir)?; }
    let path = preset_dir.join(format!("hyperx_{}.txt", name.to_lowercase().replace(" ", "_")));
    let mut content = String::from("; HyperX preset\n");
    content.push_str("Preamp: -6 dB\n\n");
    for (freq, gain) in BAND_FREQUENCIES.iter().zip(bands.iter()) {
        content.push_str(&format!("Filter: ON PK Fc {:.0} Hz Gain {:.1} dB Q 1.41\n", freq, gain));
    }
    fs::write(&path, content)?;
    log::info!("[WindowsEQ] Saved preset to {:?}", path);
    Ok(())
}

pub fn load_preset(name: &str) -> anyhow::Result<[f32; 10]> {
    let path = PathBuf::from(APO_PRESETS_DIR).join(format!("hyperx_{}.txt", name.to_lowercase().replace(" ", "_")));
    let content = fs::read_to_string(&path)?;
    let mut bands = [0.0f32; 10];
    let mut idx = 0;
    for line in content.lines() {
        if line.starts_with("Filter:") && idx < 10 {
            if let Some(gain_part) = line.split("Gain ").nth(1) {
                if let Some(gain_str) = gain_part.split(" dB").next() {
                    if let Ok(gain) = gain_str.parse::<f32>() { bands[idx] = gain; idx += 1; }
                }
            }
        }
    }
    if idx != 10 { return Err(anyhow::anyhow!("Preset file corrupted")); }
    log::info!("[WindowsEQ] Loaded preset from {:?}", path);
    Ok(bands)
}

pub fn list_presets() -> Vec<String> {
    let preset_dir = PathBuf::from(APO_PRESETS_DIR);
    if !preset_dir.exists() { return Vec::new(); }
    let mut presets = Vec::new();
    if let Ok(entries) = fs::read_dir(&preset_dir) {
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name.starts_with("hyperx_") && name.ends_with(".txt") {
                let preset = name.trim_start_matches("hyperx_").trim_end_matches(".txt").replace("_", " ");
                presets.push(preset);
            }
        }
    }
    presets
}
const APO_URL: &str = "https://sourceforge.net/projects/equalizerapo/files/1.4.2/EqualizerAPO-x64-1.4.2.exe/download";

/// Downloads the official Equalizer APO installer and runs it silently (UAC prompt, /S = NSIS silent).
/// Blocks until the installer finishes. Equalizer APO is GPLv2 and is downloaded, not bundled.
pub fn install_apo() -> anyhow::Result<()> {
    use std::os::windows::process::CommandExt;
    if is_apo_installed() { return Ok(()); }
    let script = format!(
        "$ErrorActionPreference='Stop'; $p=Join-Path $env:TEMP 'EqualizerAPO-setup.exe'; \
         [Net.ServicePointManager]::SecurityProtocol=[Net.SecurityProtocolType]::Tls12; \
         Invoke-WebRequest -UseBasicParsing -Uri '{}' -OutFile $p; \
         $r=Start-Process -FilePath $p -ArgumentList '/S' -Verb RunAs -Wait -PassThru; exit $r.ExitCode", APO_URL);
    let out = std::process::Command::new("powershell")
        .args(["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-Command", &script])
        .creation_flags(0x08000000) // CREATE_NO_WINDOW
        .output()?;
    if !out.status.success() {
        return Err(anyhow::anyhow!("Установка Equalizer APO не удалась: {}",
            String::from_utf8_lossy(&out.stderr).trim()));
    }
    if !is_apo_installed() { return Err(anyhow::anyhow!("Установщик завершился, но Equalizer APO не найден")); }
    log::info!("[WindowsEQ] Equalizer APO installed");
    Ok(())
}

/// Opens APO's Configurator so the user can tick the headset device (needs a reboot afterwards).
pub fn open_configurator() -> anyhow::Result<()> {
    let exe = PathBuf::from(APO_CONFIG_PATH).parent().and_then(|p| p.parent()).map(|p| p.join("Configurator.exe"))
        .ok_or_else(|| anyhow::anyhow!("bad APO path"))?;
    if !exe.exists() { return Err(anyhow::anyhow!("Configurator.exe не найден")); }
    std::process::Command::new(exe).spawn()?;
    Ok(())
}
